/**
 * The HTTP contract between a Host plugin and a remote node. The node build compiles this same
 * file, so a route that moves or a field that is renamed breaks the type check on the side that
 * did not change. The tunnel protocol next door is the other half of that contract.
 *
 * Nothing here may import node built-ins: the Host plugin bundles it for the browser too.
 */

/** One endpoint: the router pattern, and the URL a client builds from that same string. */
export interface NodeApiRoute {
  readonly pattern: string
  url(params?: Record<string, string>): string
}

function route(pattern: string): NodeApiRoute {
  return {
    pattern,
    url(params = {}) {
      return pattern.replace(/:([A-Za-z]+)/gu, (_match, name: string) => {
        const value = params[name]
        if (value === undefined) throw new Error(`Missing route parameter: ${name}`)
        return encodeURIComponent(value)
      })
    },
  }
}

/**
 * Every path the node owns. A route that is not listed here is not part of the contract: the node
 * proxies it to the paired Host instead.
 */
export const NODE_API = {
  discovery: route('/.well-known/dsh-remote'),
  health: route('/healthz'),
  config: route('/v1/config'),
  assets: route('/v1/assets'),
  asset: route('/assets/:hid/:rev/*'),
  hosts: route('/v1/hosts'),
  host: route('/v1/hosts/:hostId'),
  hostDevice: route('/v1/hosts/:hostId/devices/:deviceId'),
  pairings: route('/v1/pairings'),
  pairing: route('/v1/pairings/:requestId'),
  pairingClaim: route('/v1/pairings/claim'),
  pairingConfirm: route('/v1/pairings/:requestId/confirm'),
  pairingReject: route('/v1/pairings/:requestId/reject'),
} as const

/** The complete capability whitelist: an unknown capability means a protocol the client must refuse. */
export const NODE_CAPABILITIES = ['pairing', 'cache', 'official-ui'] as const
export type NodeCapability = (typeof NODE_CAPABILITIES)[number]

export const NODE_KINDS = ['gateway', 'service'] as const
export type NodeKind = (typeof NODE_KINDS)[number]

/** A Host id is the 43-character Base64URL S256 fingerprint of the Host SPKI key. */
export const HOST_ID_PATTERN = /^[A-Za-z0-9_-]{43}$/u
/** First 16 bytes of that digest, lowercase hex. */
export const FINGERPRINT_PATTERN = /^[a-f0-9]{32}$/u
/** An Ed25519 SPKI DER in base64url; the DER structure is validated where the key is parsed. */
export const PUBLIC_KEY_PATTERN = /^[A-Za-z0-9_-]{40,120}$/u
/** 1–32 characters, starting with a letter or digit: a semver fits, prose and spaces do not. */
export const NODE_VERSION_PATTERN = /^[0-9A-Za-z][0-9A-Za-z.+_-]{0,31}$/u

/** The public half of one node: two encodings of sha256(SPKI DER) plus the key itself. */
export interface NodePublicIdentity {
  id: string
  fingerprint: string
  publicKey: string
}

/** Every error the node answers with; the panel turns `code` into a sentence. */
export interface ApiErrorBody {
  code: string
  message: string
}

/** Body of `POST /v1/hosts`. A Host registers with `deviceId === hostId`. */
export interface HostRegistration {
  deviceId: string
  name: string
  identityKey: string
  clientVersion: string
}

export interface RegisteredHost {
  hostId: string
  deviceId: string
  name: string
  fingerprint: string
}

export interface HostRegistrationResult {
  credential: string
  host: RegisteredHost
}

/** What the node shows about a Host before and during pairing. */
export interface PairingHostView {
  name: string
  hostId: string
  fingerprint: string
}

/** Body of `POST /v1/pairings`; an omitted ticket is generated by the node. */
export interface PairingTicketRequest {
  ticket?: string
  expiresAt?: number
}

export interface PairingTicketResult {
  ticket: string
  expiresAt: number
  host: PairingHostView
}
